int generatePlayerHp(int rollNo) {
    return rollNo + (rand() % 901 + 100); //245826 + [100,1000] = [245926, 246826]
}

//////////////////////////////////////////////////////////////////////////////////////////

int generateEnemyHp(int rollNo) {
    int last2 = rollNo % 100;           //26
    return last2 + (rand() % 151 + 50); //26 + [50,200] = [76,226]
}

//////////////////////////////////////////////////////////////////////////////////////////

int generatePlayerDamage(int rollNo) {
    int lastDigit = rollNo % 10;    //6
    return lastDigit + 10;          //6 + 10 = 16
}

//////////////////////////////////////////////////////////////////////////////////////////

int generateEnemyDamage(int rollNo) {
    int secondLast = (rollNo / 10) % 10;    //2
    return secondLast + 10;                 //2 + 10 = 12
}

//////////////////////////////////////////////////////////////////////////////////////////

int generatePlayerSpeed(int playerCount) {
    if (playerCount <= 0) return 25;
    int speed = 100 / playerCount;
    if (speed > 25) speed = 25;
    return speed;
}

//////////////////////////////////////////////////////////////////////////////////////////

int generateEnemySpeed() {
    return rand() % 21 + 10; //random between 10 and 30
}

//////////////////////////////////////////////////////////////////////////////////////////

int generateEnemyCount() {
    return rand() % 8 + 2; //random between 2 and 9
}

